/**
 * Trả về Icon SVG phù hợp cho từng món đồ
 */
export function getItemSvgIcon(item, size = 22, color = 'currentColor') {
  const name = (item.displayName || '').toLowerCase();
  const code = (item.catalogItemCode || item.itemType || '').toUpperCase();

  if (name.includes('sofa') || name.includes('salon') || code === 'SOFA') {
    return <SofaIcon size={size} color={color} />;
  }
  if (name.includes('nệm') || name.includes('đệm') || name.includes('mattress') || code === 'MATTRESS') {
    return <BedIcon size={size} color={color} />;
  }
  if (name.includes('tủ') || name.includes('cabinet') || name.includes('wardrobe') || code === 'CABINET') {
    return <CabinetIcon size={size} color={color} />;
  }
  if (name.includes('bàn') || name.includes('ghế') || name.includes('table') || name.includes('chair') || code === 'TABLE') {
    return <TableIcon size={size} color={color} />;
  }
  return <BoxIcon size={size} color={color} />;
}
